export function asSearchTag(q: string) {
  const t = q.replace(/^#/, '').trim()
  return t ? `#${t}` : ''
}

export function bareQuery(q: string) {
  return q.replace(/^#/, '').trim()
}

export function getSetById(id: string) {
  return EMOTICON_SETS.find((set) => set.id === id) ?? null
}

export function searchSets(query: string) {
  const q = bareQuery(query).toLowerCase()
  if (!q) return []
  return EMOTICON_SETS.filter((set) => {
    const hay = [set.title, set.characterName, set.creatorName, set.category, set.seriesName, ...set.tags]
      .join(' ')
      .toLowerCase()
    return hay.includes(q)
  })
}

export function recommendedSets() {
  return EMOTICON_SETS.filter((set) => set.isRecommended)
}

export function newSets() {
  return [...EMOTICON_SETS].sort((a, b) => b.createdAt.localeCompare(a.createdAt))
}
