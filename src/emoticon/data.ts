function remapItems(items: (typeof RAW_SETS)[number]['emoticons'], setId: string, character: string) {
  return items.map((item, i) => ({
    ...item,
    id: `${setId}-${String(i + 1).padStart(2, '0')}`,
    setId,
    tags: [item.name, character],
  }))
}

function splitPack(
  set: (typeof RAW_SETS)[number],
  a: { id: string; title: string; characterName: string; description: string; tags: string[]; createdAt: string; isNew: boolean; isRecommended: boolean; isOwned: boolean; isFavorite: boolean },
  b: { id: string; title: string; characterName: string; description: string; tags: string[]; createdAt: string; isNew: boolean; isRecommended: boolean; isOwned: boolean; isFavorite: boolean },
) {
  const first = set.emoticons.slice(0, 20)
  const second = set.emoticons.slice(20, 40)
  return [
    {
      ...set,
      ...a,
      thumbnail: first[0]?.image ?? set.thumbnail,
      bannerImage: first[2]?.image ?? first[0]?.image ?? set.bannerImage,
      emoticonCount: first.length,
      emoticons: remapItems(first, a.id, a.characterName),
    },
    {
      ...set,
      ...b,
      thumbnail: second[0]?.image ?? set.thumbnail,
      bannerImage: second[2]?.image ?? second[0]?.image ?? set.bannerImage,
      emoticonCount: second.length,
      emoticons: remapItems(second, b.id, b.characterName),
    },
  ]
}

